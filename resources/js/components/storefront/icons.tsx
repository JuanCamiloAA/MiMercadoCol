/** Busca un ícono del catálogo por su nombre; si no está, cae en uno neutro. */
export function StoreIcon({
    name,
    size = 20,
    weight = 'regular',
    className,
}: {
    name?: string | null;
    size?: number;
    weight?: 'regular' | 'fill' | 'bold' | 'duotone';
    className?: string;
}) {
    const Component = ICONS[(name ?? '').replace(/Icon$/, '')] ?? PackageIcon;

    return <Component size={size} weight={weight} className={className} />;
}
